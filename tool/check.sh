#!/usr/bin/env bash
# One-command quality gate (macOS / Linux): format, analyze and test every package.
# Usage: tool/check.sh [--coverage]
set -u
root="$(cd "$(dirname "$0")/.." && pwd)"
# From the repo root, so the patrol_test glob below matches wherever this is started.
cd "$root" || exit 1
failed=()

# FVM pins the SDK locally; CI runners install the same version and use flutter/dart directly.
sdk() { if command -v fvm >/dev/null 2>&1; then fvm "$@"; else "$@"; fi; }

step() {
  local name="$1" dir="$2"; shift 2
  printf '\n== %s ==\n' "$name"
  (cd "$root/$dir" && "$@") || failed+=("$name")
}

# Runs a command in a zone with daylight saving (inside the step's subshell).
in_warsaw() { export TZ=Europe/Warsaw; "$@"; }

# patrol_test/test_bundle.dart is generated by Patrol, so only the *_test.dart files.
step 'format' . sdk dart format --output=none --set-exit-if-changed app/lib app/test app/integration_test app/patrol_test/*_test.dart app/test_driver packages/mock_data/lib packages/mock_data/test mock_server/lib mock_server/bin mock_server/test
step 'mock_data: analyze' packages/mock_data sdk dart analyze --fatal-infos
step 'mock_data: test' packages/mock_data sdk dart test
step 'mock_server: analyze' mock_server sdk dart analyze --fatal-infos
step 'mock_server: test' mock_server sdk dart test
step 'app: analyze' app sdk flutter analyze --fatal-infos
if [[ "${1:-}" == "--coverage" ]]; then
  step 'app: test' app sdk flutter test --coverage
else
  step 'app: test' app sdk flutter test
fi

# Date code across a clock change: CI runs in UTC, which never has one, so
# the calendar and day-window tests run again where 25 Oct has 25 hours.
step 'app: dates in Europe/Warsaw' app in_warsaw sdk flutter test test/core/time
step 'mock_data: dates in Europe/Warsaw' packages/mock_data in_warsaw sdk dart test --plain-name 'calendar midnight'

if ((${#failed[@]})); then printf '\nFAILED: %s\n' "${failed[*]}"; exit 1; fi
printf '\nAll checks passed.\n'
