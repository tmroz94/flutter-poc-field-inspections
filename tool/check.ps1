# One-command quality gate: format, analyze and test every package.
# Usage: pwsh tool/check.ps1   (add -Coverage for lcov output in app/coverage)
param([switch]$Coverage)
$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot -Parent
# FVM pins the SDK from .fvmrc; without it, flutter/dart from PATH (like check.sh).
$fvm = (Get-Command fvm -ErrorAction SilentlyContinue).Source
if (-not $fvm) { Write-Host 'FVM not found: using flutter/dart from PATH.' -ForegroundColor Yellow }
$failed = @()

# `Sdk dart format …` runs `fvm dart format …`, or `dart format …` without FVM.
function Sdk {
  if ($fvm) { & $fvm @args } else { $exe, $rest = $args; & $exe @rest }
}

function Step([string]$name, [string]$dir, [scriptblock]$cmd) {
  Write-Host "`n== $name ==" -ForegroundColor Cyan
  Push-Location (Join-Path $root $dir)
  try { & $cmd; if ($LASTEXITCODE -ne 0) { $script:failed += $name } } finally { Pop-Location }
}

# patrol_test/test_bundle.dart is generated by Patrol, so only the *_test.dart files.
Step 'format' '.' { Sdk dart format --output=none --set-exit-if-changed app/lib app/test app/integration_test (Get-ChildItem app/patrol_test -Filter *_test.dart).FullName app/test_driver packages/mock_data/lib packages/mock_data/test mock_server/lib mock_server/bin mock_server/test tool }
Step 'mock_data: analyze' 'packages/mock_data' { Sdk dart analyze --fatal-infos }
Step 'mock_data: test' 'packages/mock_data' { Sdk dart test }
Step 'mock_server: analyze' 'mock_server' { Sdk dart analyze --fatal-infos }
Step 'mock_server: test' 'mock_server' { Sdk dart test }
Step 'app: analyze' 'app' { Sdk flutter analyze --fatal-infos }
Step 'app: test' 'app' { if ($Coverage) { Sdk flutter test --coverage } else { Sdk flutter test } }
Step 'tool: analyze' 'tool' { Sdk dart analyze --fatal-infos . }

# Generated code must match its sources: regenerate (drift's output is then
# formatted like the rest) and compare, ignoring line endings.
$generated = @(Join-Path $root 'app/lib/data/local/app_database.g.dart') + (Get-ChildItem (Join-Path $root 'app/lib/l10n/generated') -Filter *.dart).FullName
function Snapshot { ($generated | ForEach-Object { (Get-Content -Raw $_) -replace "`r`n", "`n" }) -join "`n---`n" }
Step 'generated code' 'app' {
  $raw = @{}; foreach ($g in $generated) { $raw[$g] = [IO.File]::ReadAllBytes($g) }
  $before = Snapshot
  Sdk dart run build_runner build --delete-conflicting-outputs | Out-Null
  if ($LASTEXITCODE -eq 0) { Sdk dart format lib/data/local/app_database.g.dart | Out-Null }
  if ($LASTEXITCODE -eq 0) { Sdk flutter gen-l10n | Out-Null }
  if ($LASTEXITCODE -ne 0) { return }
  if ((Snapshot) -ne $before) {
    Write-Host 'Generated code was out of date. It has been regenerated: review and commit it.' -ForegroundColor Yellow
    $global:LASTEXITCODE = 1
  } else {
    # Same code: put back the files as they were (the generators write LF line endings).
    foreach ($g in $generated) { [IO.File]::WriteAllBytes($g, $raw[$g]) }
  }
}

# The Europe/Warsaw date run is in check.sh only: Dart on Windows ignores TZ.
if ($failed.Count) { Write-Host "`nFAILED: $($failed -join ', ')" -ForegroundColor Red; exit 1 }
Write-Host "`nAll checks passed." -ForegroundColor Green
