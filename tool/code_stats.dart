// Counts shared vs platform-specific code and writes the numbers that the
// Diagnostics screen (P24) shows. Run from the repo root:
//   fvm dart tool/code_stats.dart
//
// Shared: Dart in app/lib (generated l10n excluded), minus the files that only
// compile on one platform. Platform-specific: those Dart files plus the
// hand-written native files (Kotlin, Swift, manifests, Info.plist, web shell).
import 'dart:io';

const _platformDart = ['app/lib/core/platform/web_bridge_web.dart', 'app/lib/core/platform/web_bridge_stub.dart'];
const _native = [
  'app/android/app/src/main/kotlin',
  'app/android/app/src/main/AndroidManifest.xml',
  'app/ios/Runner/AppDelegate.swift',
  'app/ios/Runner/SceneDelegate.swift',
  'app/ios/Runner/Info.plist',
  'app/web/index.html',
  'app/web/manifest.json',
];
final _capabilityCheck = RegExp(
  r'kIsWeb|\.isWeb\b|\.isMobile\b|\.biometricLock\b|\.haptics\b|\.openSystemSettings\b|\.pullToRefreshOnly\b',
);

int _lines(File f) {
  var n = 0;
  for (final raw in f.readAsLinesSync()) {
    final l = raw.trim();
    if (l.isEmpty || l.startsWith('//') || l.startsWith('<!--') || l.startsWith('*')) continue;
    n++;
  }
  return n;
}

Iterable<File> _files(String path) {
  final type = FileSystemEntity.typeSync(path);
  if (type == FileSystemEntityType.file) return [File(path)];
  if (type == FileSystemEntityType.directory) return Directory(path).listSync(recursive: true).whereType<File>();
  return const [];
}

void main() {
  var shared = 0;
  var platform = 0;
  var checks = 0;
  for (final f in Directory('app/lib').listSync(recursive: true).whereType<File>()) {
    final path = f.path.replaceAll(r'\', '/');
    if (!path.endsWith('.dart') || path.contains('/l10n/generated/') || path.endsWith('code_stats.g.dart')) continue;
    if (_platformDart.contains(path)) {
      platform += _lines(f);
    } else {
      shared += _lines(f);
      checks += _capabilityCheck.allMatches(f.readAsStringSync()).length;
    }
  }
  for (final p in _native) {
    for (final f in _files(p)) {
      platform += _lines(f);
    }
  }
  final percent = (shared * 1000 / (shared + platform)).round() / 10;
  File('app/lib/core/app/code_stats.g.dart').writeAsStringSync('''
// Generated by tool/code_stats.dart. Do not edit.

/// Lines of shared Dart vs platform-specific code (Dart + native).
const codeStats = (shared: $shared, platformSpecific: $platform, capabilityChecks: $checks, sharedPercent: $percent);
''');
  stdout.writeln(
    'Shared: $shared lines · platform-specific: $platform lines · $percent% shared · $checks capability checks in shared code',
  );
}
